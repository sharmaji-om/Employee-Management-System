CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE departments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL,
 description VARCHAR(300) NOT NULL DEFAULT '',
 version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_department_name ON departments (LOWER(name));
CREATE TABLE employees (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR(100) NOT NULL,
 email VARCHAR(254) NOT NULL,
 phone VARCHAR(25) NOT NULL,
 department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE RESTRICT,
 designation VARCHAR(100) NOT NULL,
 joining_date DATE NOT NULL,
 salary NUMERIC(14,2) NOT NULL CHECK (salary >= 0),
 status VARCHAR(10) NOT NULL CHECK (status IN ('ACTIVE','INACTIVE')),
 version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_employee_email ON employees (LOWER(email));
CREATE INDEX ix_employee_department_status ON employees (department_id,status);
CREATE INDEX ix_employee_status ON employees(status);
CREATE INDEX ix_employee_name ON employees(LOWER(full_name));
